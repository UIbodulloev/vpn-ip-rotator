MODES = """🔀 Режимы смены адреса

▪️ replace-ip — рабочая лошадка
Сервер останавливается, получает новый IPv4, старый освобождается, сервер
стартует. Даунтайм 2-3 минуты, денег не стоит. Это выбор по умолчанию.

▪️ recreate — переезд
Снимается шаблон системного диска, из него поднимается новый сервер (можно в
другой стране), старый удаляется. Даунтайм 5-10 минут в своей зоне и до
получаса при переезде. Адрес бесплатный, а неиспользованное время старого
сервера возвращается на счёт.
Шаблон тянет за собой всё: ключи, базу клиентов, настройки. Старые конфиги
после переезда продолжают работать.
Нужен, когда заблокирован не адрес, а вся подсеть провайдера.

▪️ floating — без даунтайма
Плавающий адрес поднимается на живом сервере через SSH, разрыва нет.
Стоит около $3.5 в месяц за адрес и требует SSH-ключа.

▪️ auto — лестница (рекомендуется)
1. Первая блокировка → replace-ip.
2. Новый адрес умер меньше чем за 6 часов → значит дело не в адресе, а в
   подсети → recreate в другую зону.
3. Заблокировано и после переезда → агент останавливается и зовёт вас.
   Дальше менять адреса бессмысленно: проблема в протоколе, надо менять порт,
   SNI/dest у Reality или транспорт.

Переключить: /mode auto (или replace-ip / recreate / floating)"""

